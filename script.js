const TYPOGRAPHY_SKIP_TAGS = new Set([
  "CODE",
  "INPUT",
  "NOSCRIPT",
  "OPTION",
  "PRE",
  "SCRIPT",
  "STYLE",
  "TEXTAREA",
]);

const SHORT_WORDS_PATTERN =
  /(?<![\p{L}\p{N}])(между|через|без|для|над|обо|под|при|про|во|до|за|из|на|не|ни|но|об|от|по|со|а|в|и|к|о|с|у|я)\s+(?=\S)/giu;

function applyTypography(root = document.body) {
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
    acceptNode(node) {
      const parent = node.parentElement;
      if (!parent || TYPOGRAPHY_SKIP_TAGS.has(parent.tagName)) {
        return NodeFilter.FILTER_REJECT;
      }

      return /\S\s+\S/u.test(node.nodeValue)
        ? NodeFilter.FILTER_ACCEPT
        : NodeFilter.FILTER_REJECT;
    },
  });
  const textNodes = [];

  while (walker.nextNode()) textNodes.push(walker.currentNode);

  textNodes.forEach((node) => {
    node.nodeValue = node.nodeValue.replace(SHORT_WORDS_PATTERN, "$1\u00a0");
  });
}

